CREATE TABLE operator_feed_cooldown(
 scope VARCHAR(40) PRIMARY KEY CHECK(scope='UPSTOX_OPERATOR'),
 failure_code VARCHAR(60) NOT NULL CHECK(failure_code IN
 ('UPSTOX_REAUTHORIZATION_REQUIRED','UPSTOX_ACCESS_OR_ENTITLEMENT_REJECTED','PROVIDER_RATE_LIMITED','PROVIDER_TEMPORARY_FAILURE','PROVIDER_TRANSPORT_FAILURE')),
 failure_count INT NOT NULL CHECK(failure_count BETWEEN 1 AND 7),
 last_failure_at TIMESTAMPTZ NOT NULL,
 blocked_until TIMESTAMPTZ NOT NULL
);
